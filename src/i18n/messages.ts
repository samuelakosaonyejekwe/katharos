function widen(rows: Record<string, Six>, extraKey: 'msg' | 'ui'): Record<string, Texts> {
  const out: Record<string, Texts> = {};
  for (const [k, row] of Object.entries(rows)) {
    const t: Texts = {};
    ORDER.forEach((l, i) => (t[l] = row[i]));
    for (const [l, cat] of Object.entries(EXTRA)) if (cat?.[extraKey]?.[k]) t[l as Lang] = cat[extraKey][k];
    out[k] = t;
  }
  return out;
}

export const MSG: Record<string, Texts> = widen(MSG6, 'msg');

export function msg(key: string, lang: Lang, params: Record<string, string | number> = {}): string {
  const row = MSG[key];
  if (!row) return key;
  return fill(row[lang] || row.en || key, params);
}

